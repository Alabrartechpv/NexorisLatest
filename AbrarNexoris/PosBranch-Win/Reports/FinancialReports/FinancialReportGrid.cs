        internal FinancialReportGrid(Form owner, UltraGrid grid, UltraPanel footer, Func<string> getLayoutKey,
            params string[] sumColumns)
        {
            this.owner = owner;
            gridReport = grid;
            ultraPanelGridFooter = footer;
            this.getLayoutKey = getLayoutKey;
            summaryDefaultNumericColumns = new HashSet<string>(sumColumns, StringComparer.OrdinalIgnoreCase);
            _footerLabels = new Dictionary<string, Label>(StringComparer.OrdinalIgnoreCase);
            _columnAggregations = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);

            grid.AfterColPosChanged += (s, e) =>
            {
                RefreshFooter();
                SaveLayout();
            };
            grid.AfterColRegionScroll += (s, e) => UpdateFooterCellPositions();
            grid.AfterRowRegionScroll += (s, e) => UpdateFooterCellPositions();
            grid.Paint += (s, e) => UpdateFooterCellPositions();
            grid.Resize += (s, e) => UpdateFooterCellPositions();
            grid.AfterRowFilterChanged += (s, e) =>
            {
                UpdateFooterValues();
                UpdateFooterCellPositions();
            };
            grid.AfterSortChange += (s, e) => UpdateFooterValues();
            footer.Resize += (s, e) => UpdateFooterCellPositions();
            owner.Disposed += (s, e) =>
            {
                foreach (Label label in _footerLabels.Values)
                    label.ContextMenuStrip?.Dispose();
                headerToolTip.Dispose();
                columnChooserForm?.Dispose();
            };
        }

